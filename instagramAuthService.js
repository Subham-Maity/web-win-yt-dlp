const { spawn } = require('child_process');
const path = require('path');
const os = require('os');
const fs = require('fs');

/**
 * Searches for Google Chrome or Microsoft Edge executable on Windows.
 */
function findBrowserExe() {
  const candidates = [
    'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
    'C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe',
    path.join(os.homedir(), 'AppData\\Local\\Google\\Chrome\\Application\\chrome.exe'),
    'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',
    'C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe',
    path.join(os.homedir(), 'AppData\\Local\\Microsoft\\Edge\\Application\\msedge.exe')
  ];

  for (const p of candidates) {
    if (fs.existsSync(p)) return p;
  }
  return null;
}

let activeAuthSession = null;

/**
 * Merges newly captured Instagram cookies into cookies.txt, preserving non-Instagram cookies.
 */
function mergeCookiesIntoFile(newCookiesList, cookiesFilePath) {
  let existingLines = [];
  if (fs.existsSync(cookiesFilePath)) {
    try {
      const content = fs.readFileSync(cookiesFilePath, 'utf8');
      existingLines = content.split('\n')
        .map(l => l.trim())
        .filter(l => l && !l.startsWith('#') && !l.includes('instagram.com')); // strip old instagram cookies & comments
    } catch (_) {}
  }

  // Deduplicate new cookies by name
  const cookieMap = new Map();
  for (const c of newCookiesList) {
    if (c && c.name && c.value) {
      cookieMap.set(c.name, c);
    }
  }

  const newLines = Array.from(cookieMap.values()).map(c => {
    const domain = c.domain || '.instagram.com';
    const sub = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const path = c.path || '/';
    const sec = c.secure !== false ? 'TRUE' : 'FALSE';
    const exp = Math.round(c.expires > 0 ? c.expires : (Date.now() / 1000) + (365 * 86400));
    return `${domain}\t${sub}\t${path}\t${sec}\t${exp}\t${c.name}\t${c.value}`;
  });

  const header = [
    '# Netscape HTTP Cookie File',
    '# Generated by yt-dlp-web Instagram Login'
  ];

  const finalContent = [...header, ...existingLines, ...newLines].join('\n') + '\n';
  fs.writeFileSync(cookiesFilePath, finalContent, 'utf8');
}

/**
 * Manually saves a sessionid, full Netscape cookie text, or Cookie-Editor JSON into cookies.txt
 */
function saveManualSession(inputData, dsUserId, cookiesFilePath) {
  if (!inputData || typeof inputData !== 'string') {
    throw new Error('Valid cookie content or sessionid string is required.');
  }

  let text = inputData.trim();

  // 1. Check if user pasted JSON array from Cookie-Editor
  if (text.startsWith('[') && text.endsWith(']')) {
    try {
      const arr = JSON.parse(text);
      if (Array.isArray(arr) && arr.length > 0) {
        const cookies = arr.map(c => ({
          name: c.name,
          value: c.value,
          domain: c.domain || '.instagram.com',
          path: c.path || '/',
          secure: c.secure !== false,
          expires: c.expirationDate || (Date.now() / 1000) + (365 * 86400)
        }));
        mergeCookiesIntoFile(cookies, cookiesFilePath);
        const userC = cookies.find(c => c.name === 'ds_user_id');
        return { success: true, userId: userC ? userC.value : '' };
      }
    } catch (_) {}
  }

  // 2. Check if user pasted Netscape format text (e.g. from Cookie-Editor export)
  if (text.includes('.instagram.com') || (text.includes('sessionid') && text.includes('\t'))) {
    const lines = text.split('\n').map(l => l.trim()).filter(Boolean);
    const parsedCookies = [];
    for (const rawLine of lines) {
      let line = rawLine.replace(/#HttpOnly_/g, '');
      if (line.startsWith('#')) continue;
      const parts = line.split('\t');
      if (parts.length >= 7) {
        parsedCookies.push({
          domain: parts[0],
          path: parts[2],
          secure: parts[3] === 'TRUE',
          expires: parseInt(parts[4], 10) || (Date.now() / 1000) + (365 * 86400),
          name: parts[5],
          value: parts[6]
        });
      }
    }
    if (parsedCookies.length > 0) {
      mergeCookiesIntoFile(parsedCookies, cookiesFilePath);
      const userC = parsedCookies.find(c => c.name === 'ds_user_id');
      return { success: true, userId: userC ? userC.value : '' };
    }
  }

  // 3. Simple sessionid string
  if (text.startsWith('http://') || text.startsWith('https://')) {
    throw new Error('You pasted a web URL. Please paste your Instagram sessionid or exported cookies.');
  }

  const cleanSession = text.replace(/^sessionid\s*=\s*/i, '').trim();
  if (cleanSession.length < 10 || cleanSession.includes(' ') || cleanSession.includes('/')) {
    throw new Error('Invalid Instagram session format. Please paste a valid sessionid or export from Cookie-Editor.');
  }

  let uid = (dsUserId || '').trim();
  if (!uid && cleanSession.includes('%3A')) {
    uid = cleanSession.split('%3A')[0];
  } else if (!uid && cleanSession.includes(':')) {
    uid = cleanSession.split(':')[0];
  }

  const cookiesToSave = [
    { name: 'sessionid', value: cleanSession, domain: '.instagram.com', path: '/', secure: true, expires: (Date.now() / 1000) + (365 * 86400) }
  ];

  if (uid) {
    cookiesToSave.push({ name: 'ds_user_id', value: uid, domain: '.instagram.com', path: '/', secure: true, expires: (Date.now() / 1000) + (365 * 86400) });
  }

  mergeCookiesIntoFile(cookiesToSave, cookiesFilePath);
  return { success: true, userId: uid };
}

/**
 * Launches an interactive Chrome/Edge popup window with Instagram login and captures
 * cookies via Chrome DevTools Protocol (CDP) as soon as the user logs in.
 */
function startInstagramLoginPopup({ cookiesFilePath, onBroadcast, onCompleted, onError }) {
  if (activeAuthSession) {
    try {
      if (activeAuthSession.proc) activeAuthSession.proc.kill();
      if (activeAuthSession.pollTimer) clearInterval(activeAuthSession.pollTimer);
    } catch (_) {}
    activeAuthSession = null;
  }

  const browserExe = findBrowserExe();
  if (!browserExe) {
    throw new Error('Neither Google Chrome nor Microsoft Edge was found on your system. Please use manual session paste.');
  }

  const port = 9222;
  const userDataDir = path.join(os.homedir(), 'AppData', 'Local', 'yt-dlp-web', 'ig_browser_profile');
  if (!fs.existsSync(userDataDir)) {
    fs.mkdirSync(userDataDir, { recursive: true });
  }

  const args = [
    `--remote-debugging-port=${port}`,
    `--user-data-dir=${userDataDir}`,
    '--no-first-run',
    '--no-default-browser-check',
    '--new-window',
    'https://www.instagram.com/accounts/login/'
  ];

  const proc = spawn(browserExe, args, {
    detached: true,
    stdio: 'ignore'
  });
  proc.unref();

  let isDone = false;
  let pollTimer = null;
  let attempts = 0;
  let connectedOnce = false;

  const cleanup = () => {
    isDone = true;
    if (pollTimer) clearInterval(pollTimer);
    activeAuthSession = null;
  };

  activeAuthSession = { cleanup };

  // Poll CDP every 1500ms
  pollTimer = setInterval(async () => {
    if (isDone) return;
    attempts++;

    try {
      const res = await fetch(`http://127.0.0.1:${port}/json`).catch(() => null);
      if (!res || !res.ok) {
        if (connectedOnce && attempts > 15) {
          // Window was open and was closed by user
          cleanup();
          if (onBroadcast) onBroadcast({ type: 'instagram_auth_closed', message: 'Browser window closed.' });
        }
        return;
      }

      connectedOnce = true;

      const targets = await res.json();
      const page = targets.find(t => t.type === 'page' && (t.url.includes('instagram.com') || t.title.includes('Instagram')));
      if (!page || !page.webSocketDebuggerUrl) return;

      if (typeof WebSocket === 'undefined') return;

      const ws = new WebSocket(page.webSocketDebuggerUrl);

      ws.onopen = () => {
        ws.send(JSON.stringify({
          id: 1,
          method: 'Network.getCookies',
          params: { urls: ['https://www.instagram.com', 'https://instagram.com'] }
        }));
      };

      ws.onmessage = (event) => {
        try {
          const msg = JSON.parse(event.data);
          if (msg.id === 1 && msg.result && Array.isArray(msg.result.cookies)) {
            const cookies = msg.result.cookies;
            const sessionCookie = cookies.find(c => c.name === 'sessionid');
            const userCookie = cookies.find(c => c.name === 'ds_user_id');

            if (sessionCookie && sessionCookie.value) {
              // Successfully captured logged-in Instagram session!
              cleanup();

              const igCookies = cookies.filter(c => c.domain.includes('instagram.com'));
              mergeCookiesIntoFile(igCookies, cookiesFilePath);

              const userId = userCookie ? userCookie.value : '';
              if (onBroadcast) {
                onBroadcast({
                  type: 'instagram_auth_success',
                  userId,
                  message: `Instagram session captured successfully! Logged in as User ID: ${userId}`
                });
              }
              if (onCompleted) {
                onCompleted({ success: true, userId, cookies: igCookies });
              }
            }
          }
        } catch (_) {}
        try { ws.close(); } catch (_) {}
      };

      ws.onerror = () => {
        try { ws.close(); } catch (_) {}
      };
    } catch (_) {}
  }, 1500);

  // Timeout after 5 minutes
  setTimeout(() => {
    if (!isDone) {
      cleanup();
      if (onError) onError(new Error('Instagram login timed out after 5 minutes.'));
    }
  }, 300000);

  return { success: true, browser: path.basename(browserExe) };
}

function cancelInstagramLoginPopup() {
  if (activeAuthSession && activeAuthSession.cleanup) {
    activeAuthSession.cleanup();
    return true;
  }
  return false;
}

/**
 * Opens Instagram in the default system browser
 */
function openInstagramInBrowser() {
  const { exec } = require('child_process');
  if (process.platform === 'win32') {
    exec('start https://www.instagram.com/accounts/login/');
  } else if (process.platform === 'darwin') {
    exec('open https://www.instagram.com/accounts/login/');
  } else {
    exec('xdg-open https://www.instagram.com/accounts/login/');
  }
  return true;
}

/**
 * Returns current Instagram cookie status from cookies.txt
 */
function getInstagramSessionStatus(cookiesFilePath) {
  let hasSession = false;
  let userId = '';
  let cookieCount = 0;
  let lastModified = null;

  if (fs.existsSync(cookiesFilePath)) {
    try {
      const stats = fs.statSync(cookiesFilePath);
      lastModified = stats.mtime;
      const content = fs.readFileSync(cookiesFilePath, 'utf8');
      const lines = content.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'));
      cookieCount = lines.filter(l => l.includes('instagram.com')).length;
      hasSession = content.includes('sessionid') && content.includes('.instagram.com');

      const userMatch = content.match(/ds_user_id\t([0-9]+)/);
      if (userMatch && userMatch[1]) {
        userId = userMatch[1];
      } else {
        const sMatch = content.match(/sessionid\t([0-9]+)%3A/);
        if (sMatch && sMatch[1]) userId = sMatch[1];
      }
    } catch (_) {}
  }

  return {
    hasSession,
    userId,
    cookieCount,
    lastModified
  };
}

/**
 * Removes Instagram cookies from cookies.txt
 */
function clearInstagramSession(cookiesFilePath) {
  if (fs.existsSync(cookiesFilePath)) {
    try {
      const content = fs.readFileSync(cookiesFilePath, 'utf8');
      const lines = content.split('\n').filter(l => !l.includes('instagram.com'));
      fs.writeFileSync(cookiesFilePath, lines.join('\n'), 'utf8');
      return true;
    } catch (_) {}
  }
  return false;
}

